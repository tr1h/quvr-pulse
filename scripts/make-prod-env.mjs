// Builds .env.production from the local .env for the VPS. Never prints secret values.
//   node scripts/make-prod-env.mjs --ip 1.2.3.4            (no domain yet: http, Telegram polling)
//   node scripts/make-prod-env.mjs --domain quvrpulse.com   (https via Caddy, Telegram webhook)
// Re-running keeps generated secrets (database password, webhook secret) from the existing file.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";

const args = Object.fromEntries(
  process.argv
    .slice(2)
    .reduce(
      (acc, a, i, all) => (a.startsWith("--") ? [...acc, [a.slice(2), all[i + 1]]] : acc),
      [],
    ),
);
const host = /^[a-z0-9.-]+$/i;
if (
  (!args.ip && !args.domain) ||
  (args.ip && !host.test(args.ip)) ||
  (args.domain && !host.test(args.domain))
) {
  console.error("usage: node scripts/make-prod-env.mjs --ip <server-ip> | --domain <domain>");
  process.exit(1);
}

const parse = (file) =>
  existsSync(file)
    ? Object.fromEntries(
        readFileSync(file, "utf8")
          .split(/\r?\n/)
          .filter((l) => l && !l.startsWith("#") && l.includes("="))
          .map((l) => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim()]),
      )
    : {};

const local = parse(".env");
const prev = parse(".env.production");
const secret = () => randomBytes(24).toString("hex");

const drop = new Set(["DATABASE_URL", "REDIS_URL"]); // set by docker-compose.prod.yml
const out = Object.fromEntries(Object.entries(local).filter(([k]) => !drop.has(k)));
out.POSTGRES_PASSWORD = prev.POSTGRES_PASSWORD || secret();
out.TELEGRAM_WEBHOOK_SECRET = prev.TELEGRAM_WEBHOOK_SECRET || secret();
out.LOG_LEVEL = "info";
if (args.domain) {
  out.SITE_ADDRESS = `${args.domain}, www.${args.domain}`;
  out.NEXT_PUBLIC_APP_URL = `https://${args.domain}`;
  out.TELEGRAM_MODE = "webhook";
} else {
  out.SITE_ADDRESS = ":80";
  out.NEXT_PUBLIC_APP_URL = `http://${args.ip}`;
  out.TELEGRAM_MODE = "polling"; // Telegram webhooks require https
}

writeFileSync(
  ".env.production",
  `# Generated by scripts/make-prod-env.mjs — contains secrets, never commit.\n` +
    Object.entries(out)
      .map(([k, v]) => `${k}=${v}`)
      .join("\n") +
    "\n",
);
console.log(
  `.env.production written (${Object.keys(out).length} keys): ${Object.keys(out).join(", ")}`,
);
